inline const Track& track(Actor a,Pose p,bool sockbug) {
    const unsigned row=a==Actor::Penny && sockbug?24:static_cast<unsigned>(a);
    const unsigned i=indices[row][static_cast<unsigned>(p)];
    return tracks[i==255?indices[row][0]:i];
}
inline unsigned frame(const Track& t,unsigned ms) {
    const uint64_t elapsed=uint64_t(ms)*1000;
    const unsigned us=t.loop?static_cast<unsigned>(elapsed%t.lengthUs):
        static_cast<unsigned>(elapsed>=t.lengthUs?t.lengthUs-1:elapsed);
    for(unsigned i=0;i<t.count;++i)if(us<frames[t.first+i].endUs)return frames[t.first+i].sprite;
    return frames[t.first+t.count-1].sprite;
}
